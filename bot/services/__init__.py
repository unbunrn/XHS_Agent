"""Business services.  Adapters never write state; services own the rules."""

# 中文说明：
# 这个包是整个机器人的“业务规则层”，可以理解成公司的规章制度执行部门：
#   - research.py       采集入库、去重聚类、打分选题、整理证据
#   - drafts.py         把证据交给模型写稿，校验后渲染 PNG，再发起审批
#   - approvals.py      审批的生命周期和“绑定”校验（正文/图片/账号/时间）
#   - notifications.py  把审批消息排队并投递到飞书或本地文件
#   - topics.py         手机飞书“选题/写一篇”委托：持久请求、定向检索、配额延后
#   - publish.py        发布闸门：只有它有权调用发布适配器
#   - analytics.py      发布后的数据快照（拿不到就明确写“缺失”，不造数）
#
# 为什么把规则单独放一层？
#   适配器可能被替换（假模型换真模型、mock 换真实平台），但“必须审批”
#   “同一版本只能发布一次”“发布结果未知不能重试”这些规则绝不能跟着变。
#   所以规则集中在这里，适配器再换也绕不过去。
