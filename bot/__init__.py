"""Persistent single-account AI news operator.

The package is deliberately stdlib-first.  Pillow is required for local PNG
rendering, ``lark-oapi`` is only required when the Feishu channel is enabled.
"""

# =============================================================================
# 中文导读（本文件只增加注释，没有改动任何代码）
# =============================================================================
# 整个项目是一个“本地运营机器人”，可以把它想象成一家只有一名员工的编辑部：
#
#   采集员  -> 从 RSS / 本地样例文件读取 AI 新闻
#   研究员  -> 去重、聚类、打分，挑出值得写的选题
#   撰稿人  -> 调用 DeepSeek（或离线假模型）生成结构化草稿
#   美工    -> 用 Pillow 把草稿排版成 1080x1440 的 PNG 卡片
#   审批员  -> 把最终版本发到飞书私聊或本机网页，等账号主人批准
#   发布员  -> 只有“批准 + 所有检查通过”才调用发布适配器
#   档案员  -> 所有状态写进 SQLite，进程重启后还能接着干
#
# 这个包为什么坚持“尽量只用标准库”？
#   - 初学者容易跑起来：少装一个依赖，就少一类环境问题；
#   - 安全边界更小：外部依赖越少，能被利用的代码越少；
#   - 只有两个例外：Pillow 用来画 PNG（必须有），lark-oapi 只在接飞书时才用。
#
# 阅读顺序建议：
#   1. bot/config.py       配置怎么加载、密钥放在哪
#   2. bot/schema.py       SQLite 里有哪些表（整个系统的“账本”）
#   3. bot/db.py           数据库连接与事务的薄封装
#   4. bot/worker.py       主循环：一次 tick 做了什么
#   5. bot/services/       业务规则（研究、写稿、审批、发布）
#   6. bot/adapters/       外部世界适配器（RSS、DeepSeek、飞书、小红书）
#   7. bot/console.py      本机审批网页
#
# 记住一句话：适配器（adapters）只负责“和外界说话”，业务规则（services）
# 负责“能不能做”，数据库是唯一可信的状态来源。
# =============================================================================

